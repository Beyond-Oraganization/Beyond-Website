"""Publishing story changes: new pages are added, removed pages are deleted, nothing else is touched."""

import unittest

from beyondia_manager import config as cfg
from beyondia_manager import model, service
from beyondia_manager.build import build
from beyondia_manager.errors import GitError
from .helpers import GitCase, copy_fixture_site, git
from .test_stories import NEW


class StoryPublishCase(GitCase):
    def setUp(self):
        super().setUp()
        copy_fixture_site(self.work)                                    # the whole real site, so the site checks can pass
        (self.work / ".gitignore").write_text(".bm.lock\n")
        (self.work / "notes.txt").write_text("private\n")
        page = (self.work / "storygirl.html").read_text(encoding="utf-8")
        marker = [line for line in page.splitlines() if "Generated by the Beyondia site manager" in line][0]
        (self.work / "storyhand.html").write_text(page.replace(marker, "<!-- written by hand -->"), encoding="utf-8")
        self.commit_all(self.work, "initial")
        git(self.work, "push", "-u", "origin", "main")

    def edit(self, fn):
        service.apply_edit(self.work, fn)

    def publish(self, message="update", dry_run=False):
        return service.publish_site(self.work, message, dry_run=dry_run)


class AddRemoveTests(StoryPublishCase):
    def test_a_new_story_page_is_committed(self):
        self.edit(lambda c: model.add_story(c, **NEW))
        outcome = self.publish("Add the lighthouse")
        self.assertEqual(outcome.result.status, "published")
        self.assertIn("storylighthouse.html", self.remote_files())
        self.assertIn("storylighthouse.html", outcome.result.files)

    def test_a_removed_story_page_is_deleted_on_the_remote_too(self):
        self.assertIn("storyroman.html", self.remote_files())
        self.edit(lambda c: model.remove_story(c, "roman"))
        self.assertFalse((self.work / "storyroman.html").exists())
        outcome = self.publish("Remove the book")
        self.assertEqual(outcome.result.status, "published")
        self.assertNotIn("storyroman.html", self.remote_files())
        self.assertIn("storyangel.html", self.remote_files())
        self.assertEqual(git(self.work, "status", "--porcelain", "--untracked-files=no"), "")

    def test_a_draft_story_page_is_deleted_and_republished(self):
        self.edit(lambda c: model.set_story_visible(c, "roman", False))
        self.publish("Draft")
        self.assertNotIn("storyroman.html", self.remote_files())
        self.edit(lambda c: model.set_story_visible(c, "roman", True))
        self.publish("Publish again")
        self.assertIn("storyroman.html", self.remote_files())

    def test_the_stories_list_and_neighbours_are_in_the_same_commit(self):
        self.edit(lambda c: model.remove_story(c, "roman"))
        files = self.publish("x").result.files
        self.assertIn("stories.html", files)
        self.assertIn("storyroman.html", files)
        self.assertIn("site.config.json", files)

    def test_status_and_dry_run_show_a_pending_deletion(self):
        self.edit(lambda c: model.remove_story(c, "roman"))
        config = cfg.load(self.work / "site.config.json")
        summary = service.git_summary(self.work, service.managed_files(self.work, config))
        self.assertIn("storyroman.html", summary["changed"])
        remote_head = git(self.remote, "rev-parse", "main")
        outcome = self.publish("preview", dry_run=True)
        self.assertEqual(outcome.result.status, "dry-run")
        self.assertIn("storyroman.html", outcome.result.files)
        self.assertEqual(git(self.remote, "rev-parse", "main"), remote_head)
        self.assertEqual(git(self.work, "diff", "--cached", "--name-only"), "")     # dry run staged nothing


class BoundaryTests(StoryPublishCase):
    def test_other_files_are_still_never_published(self):
        (self.work / "notes.txt").write_text("edited\n")
        hand = self.work / "storyhand.html"
        hand.write_text(hand.read_text(encoding="utf-8") + "<!-- edited -->\n", encoding="utf-8")   # story-shaped, but the config does not know it
        (self.work / "secret.env").write_text("TOKEN=1\n")
        self.edit(lambda c: model.add_story(c, **NEW))
        self.publish("only managed")
        remote = self.clone_remote()
        self.assertEqual((remote / "notes.txt").read_text(), "private\n")
        self.assertNotIn("<!-- edited -->", (remote / "storyhand.html").read_text())
        self.assertNotIn("secret.env", self.remote_files())

    def test_a_hand_written_story_shaped_page_is_never_deleted_or_unpublished(self):
        self.edit(lambda c: model.remove_story(c, "roman"))
        self.publish("x")
        self.assertTrue((self.work / "storyhand.html").exists())
        self.assertIn("storyhand.html", self.remote_files())

    def test_a_deleted_file_that_is_not_a_story_page_is_not_published(self):
        (self.work / "notes.txt").unlink()                                              # not story-shaped: never published
        self.edit(lambda c: model.add_story(c, **NEW))
        self.publish("x")
        self.assertIn("notes.txt", self.remote_files())

    def test_other_staged_files_still_refuse(self):
        self.edit(lambda c: model.remove_story(c, "roman"))
        (self.work / "notes.txt").write_text("staged\n")
        git(self.work, "add", "notes.txt")
        with self.assertRaises(GitError) as ctx:
            self.publish("x")
        self.assertIn("notes.txt", str(ctx.exception))


if __name__ == "__main__":
    unittest.main()


class PostPublishTests(StoryPublishCase):
    POST = dict(id="fresh", title="A fresh post", date="2026-10-30", summary="Fresh.", body_text="Fresh text.", tags=["News"])

    def test_a_new_post_page_is_committed_with_the_list(self):
        self.edit(lambda c: model.add_post(c, **self.POST))
        outcome = self.publish("Add a post")
        self.assertEqual(outcome.result.status, "published")
        self.assertIn("blog-fresh.html", self.remote_files())
        self.assertIn("blog.html", outcome.result.files)

    def test_a_removed_post_page_is_deleted_on_the_remote(self):
        self.assertIn("blog-welcome.html", self.remote_files())
        self.edit(lambda c: model.remove_post(c, "welcome"))
        self.publish("Remove a post")
        self.assertNotIn("blog-welcome.html", self.remote_files())
        self.assertIn("blog-second-note.html", self.remote_files())

    def test_a_draft_post_page_is_deleted_and_comes_back(self):
        self.edit(lambda c: model.set_post_visible(c, "second-note", False))
        self.publish("Draft")
        self.assertNotIn("blog-second-note.html", self.remote_files())
        self.edit(lambda c: model.set_post_visible(c, "second-note", True))
        self.publish("Publish again")
        self.assertIn("blog-second-note.html", self.remote_files())

    def test_a_hand_written_blog_shaped_page_is_never_published_or_deleted(self):
        page = (self.work / "storygirl.html").read_text(encoding="utf-8")
        marker = [line for line in page.splitlines() if "Generated by the Beyondia site manager" in line][0]
        (self.work / "blog-mine.html").write_text(page.replace(marker, "<!-- by hand -->"), encoding="utf-8")
        self.edit(lambda c: model.remove_post(c, "welcome"))
        self.publish("x")
        self.assertTrue((self.work / "blog-mine.html").exists())
        self.assertNotIn("blog-mine.html", self.remote_files())
